"""`snag explore`: actively hunt for bugs, safely.

The engine drives your app with the **Playwright CLI** (not a library binding:
we shell out to `npx playwright test`), so goal-directed "missions" click around
the app while the Snag SDK records everything. Two safety layers are on by
default so nothing real can happen:

  1. Risky calls (payments / email / SMS) are intercepted and answered with a
     fake success: so nothing fires *and* Snag sees no false errors.
  2. A non-production guard refuses a prod-looking URL unless you pass --force
     and missions skip anything that looks destructive (delete / pay / send).

`scaffold` writes those Playwright helpers into your project so you can inspect
or extend them. `run` generates an ephemeral project and executes it.
"""

import json
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Any, Dict, List


def _safe_name(name: Any, i: int) -> str:
    """A filesystem-safe spec name. Never let a mission name escape the temp dir."""
    slug = re.sub(r"[^A-Za-z0-9_-]+", "-", str(name or "")).strip("-")[:48]
    return slug or f"mission-{i}"

from . import output as out
from .config import Config

# Hosts whose calls are faked with a 200 so exploration can't charge a card or
# send a message. Extend via a scaffolded config.
RISKY_HOSTS = [
    "api.stripe.com", "checkout.stripe.com", "paypal.com", "api.paypal.com",
    "api.sendgrid.com", "api.mailgun.net", "api.postmarkapp.com", "api.resend.com",
    "api.twilio.com", "hooks.slack.com", "api.sendinblue.com",
]

DESTRUCTIVE_WORDS = ["delete", "remove", "pay", "purchase", "buy", "charge",
                     "subscribe", "cancel", "deactivate", "close account", "send"]

MOCK_JS = """// Auto-mock risky third parties with a fake success, so exploration is safe.
// Generated by `snag explore scaffold`. Edit RISKY_HOSTS to taste.
const RISKY_HOSTS = %s;

async function installSafetyNet(page) {
  await page.route('**/*', async (route) => {
    const url = route.request().url();
    if (RISKY_HOSTS.some((h) => url.includes(h))) {
      return route.fulfill({ status: 200, contentType: 'application/json',
        body: JSON.stringify({ ok: true, mocked: true }) });
    }
    return route.continue();
  });
}
module.exports = { installSafetyNet, RISKY_HOSTS };
"""

SPEC_JS = """// Generated mission: do not edit by hand; `snag explore run` regenerates it.
const { test } = require('@playwright/test');
const { installSafetyNet } = require('./safety-net.js');

const START = %s;
const DESTRUCTIVE = %s;
const SAFE_MODE = %s;

test(%s, async ({ page }) => {
  await installSafetyNet(page);
  await page.goto(START, { waitUntil: 'domcontentloaded' });
  // Walk the app: fill inputs with test data, click safe buttons, follow links.
  for (let step = 0; step < 8; step++) {
    const inputs = await page.locator('input:visible, textarea:visible').all();
    for (const i of inputs.slice(0, 5)) {
      const type = (await i.getAttribute('type')) || 'text';
      try { await i.fill(type === 'email' ? 'test@example.com'
        : type === 'password' ? 'Test1234!' : 'test'); } catch (e) {}
    }
    const buttons = await page.locator('button:visible, [role=button]:visible, a[href]:visible').all();
    let clicked = false;
    for (const b of buttons) {
      const label = ((await b.innerText().catch(() => '')) || '').toLowerCase();
      if (SAFE_MODE && DESTRUCTIVE.some((w) => label.includes(w))) continue;
      try { await b.click({ timeout: 1500 }); clicked = true; break; } catch (e) {}
    }
    await page.waitForTimeout(600);
    if (!clicked) break;
  }
});
"""

CONFIG_JS = """const { defineConfig } = require('@playwright/test');
module.exports = defineConfig({
  testDir: '.', fullyParallel: true, workers: %d, retries: 0,
  reporter: [['list']], use: { headless: true, actionTimeout: 4000 },
});
"""


def _looks_prod(url: str) -> bool:
    u = url.lower()
    local = any(h in u for h in ("localhost", "127.0.0.1", "0.0.0.0", ".local",
                                 "staging", "preview", "vercel.app", "ngrok"))
    return not local


def _write_templates(dest: Path, workers: int) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "safety-net.js").write_text(MOCK_JS % json.dumps(RISKY_HOSTS), encoding="utf-8")
    (dest / "playwright.config.js").write_text(CONFIG_JS % workers, encoding="utf-8")


def scaffold(dest_dir: str) -> int:
    dest = Path(dest_dir) / "snag-explore"
    _write_templates(dest, 3)
    example = [{"name": "smoke", "url": None},
               {"name": "signup", "url": None, "goal": "complete the signup flow"}]
    (dest / "missions.json").write_text(json.dumps(example, indent=2) + "\n", encoding="utf-8")
    print(f"{out.green('OK')} wrote Playwright safety config to {dest}/")
    out.kv([("safety-net.js", "fakes payments/email/SMS with a 200"),
            ("playwright.config.js", "headless, parallel"),
            ("missions.json", "edit or let the snag-explore skill fill it")])
    return out.EXIT_OK


def _load_missions(path: str) -> List[Dict[str, Any]]:
    if path and Path(path).exists():
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        return data if isinstance(data, list) else [data]
    return [{"name": "smoke"}]


def run(url: str, missions_path: str, workers: int, force: bool, dry: bool) -> int:
    if not url:
        out.error("no URL: pass --url or set your app URL with `snag auth login`.")
        return out.EXIT_USAGE
    if _looks_prod(url) and not force:
        out.error(f"{url} looks like production.")
        out.hint("Point --url at a dev/staging server, or pass --force if you're sure.")
        return out.EXIT_USAGE

    missions = _load_missions(missions_path)
    print(out.dim(f"{len(missions)} mission(s) against {url} · {workers} workers · "
                  f"safe-mode on · payments/email mocked"))
    if dry:
        for m in missions:
            print(f"  - {m.get('name')}" + (f": {m['goal']}" if m.get("goal") else ""))
        print(out.dim("(dry run: nothing executed)"))
        return out.EXIT_OK

    if not shutil.which("npx"):
        out.error("Playwright CLI not found (needs Node + `npx playwright`).")
        out.hint("Install: npm i -D @playwright/test && npx playwright install chromium")
        return out.EXIT_ERROR

    work = Path(tempfile.mkdtemp(prefix="snag-explore-"))
    try:
        _write_templates(work, workers)
        for i, m in enumerate(missions):
            name = _safe_name(m.get("name"), i)
            # The display title keeps the original name (json-encoded, so it can
            # never break out of the JS string); only the filename is sanitized.
            spec = SPEC_JS % (json.dumps(m.get("url") or url), json.dumps(DESTRUCTIVE_WORDS),
                              json.dumps(True), json.dumps(str(m.get("name") or name)))
            (work / f"{name}.spec.js").write_text(spec, encoding="utf-8")
        env = dict(os.environ)
        proc = subprocess.run(["npx", "playwright", "test", f"--workers={workers}"],
                              cwd=str(work), env=env)
        print()
        print(f"{out.green('done')} explored {url}. Now: {out.bold('snag issue list')} "
              f"(then judge/fix/verify).")
        return out.EXIT_OK if proc.returncode == 0 else out.EXIT_OK  # test 'failures' = bugs found
    finally:
        shutil.rmtree(work, ignore_errors=True)


def dispatch(args, cfg: Config) -> int:
    verb = getattr(args, "explore_verb", None)
    if verb == "scaffold":
        return scaffold(args.dir)
    if verb == "run":
        return run(args.url or cfg.app_url, args.missions, args.workers, args.force, args.dry_run)
    out.error("usage: snag explore run|scaffold")
    return out.EXIT_USAGE
